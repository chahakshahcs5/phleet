// All returns the catalogue in a stable order.
func All() []*Engine {
	out := make([]*Engine, 0, len(registry))
	for _, e := range registry {
		out = append(out, e)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

func Get(id string) (*Engine, bool) {
	e, ok := registry[strings.ToLower(strings.TrimSpace(id))]
	return e, ok
}

// InstallCommand returns the Termux package command for an engine.
func InstallCommand(e *Engine) string {
	if e == nil || e.Package == "" {
		return ""
	}
	return "pkg install -y " + shq(e.Package)
}

// InstallScript returns the command that installs an engine. Package-based
// engines use pkg; object storage downloads static binaries instead.
func InstallScript(e *Engine, p Params) string {
	return InstallScriptFor(e, p, "pkg")
}

// InstallScriptFor renders the install command for the phone's package
// manager. Termux uses pkg; a Debian chroot or a Linux host uses apt. Engines
// with a custom Install path (rclone's static download) keep using it.
func InstallScriptFor(e *Engine, p Params, manager string) string {
	return InstallScriptAs(e, p, manager, "")
}

// InstallScriptAs is InstallScriptFor with a privilege prefix ("sudo -n " when
// the agent runs as an unprivileged user inside a Debian chroot). The prefix is
// applied to every apt invocation, never to the app or engine processes.
func InstallScriptAs(e *Engine, p Params, manager, elevate string) string {
	if e == nil {
		return ""
	}
	if manager == "apt" {
		pkg := e.AptPackage
		if pkg == "" {
			pkg = e.Package
		}
		if pkg != "" {
			// Debian's postgresql package puts initdb/pg_ctl outside PATH; the
			// agent prepends /usr/lib/postgresql/*/bin at startup.
			return elevate + "apt-get update && " + elevate + "apt-get install -y " + shq(pkg)
		}
	}
	if e.Install != nil {
		return e.Install(p)
	}
	return InstallCommand(e)
}

// EnvFor renders the environment injected into a bound project. The caller
// decides whether the project can actually reach the addon over loopback.
func EnvFor(engineID string, p Params) map[string]string {
	e, ok := Get(engineID)
	if !ok || e.Env == nil {
		return map[string]string{}
	}
	return e.Env(p)
}

// ClientCommand is the one-shot console command used by the panel. Input is
// piped on stdin, so SQL (or Redis commands) never has to survive shell
// quoting.
func ClientCommand(engineID string, p Params) string {
	e, ok := Get(engineID)
	if !ok || e.Client == nil {
		return ""
	}
	return e.Client(p)
}

// LagCommand prints the replay lag in milliseconds, or nothing when no standby
// is connected.
func LagCommand(engineID string, p Params) string {
	e, ok := Get(engineID)
	if !ok || e.Lag == nil {
		return ""
	}
	return e.Lag(p)
}

// BackupExt is the file extension used for stored backups.
func BackupExt(id string) string {
	if e, ok := Get(id); ok && e.Service {
		return ".tar.gz"
	}
	switch strings.ToLower(id) {
	case "postgres":
		return ".dump"
	case "redis":
		return ".rdb"
	case "mariadb":
		return ".sql"
	case "influxdb", "rclone", "mosquitto", "nats", "victoriametrics", "victorialogs", "ntfy", "pocketbase", "etcd", "meilisearch", "prometheus", "gitea", "beanstalkd":
		return ".tar.gz"
	case "duckdb":
		return ".duckdb"
	default:
		return ".sqlite"
	}
}

// VerifyCommand returns an engine-native integrity check for a downloaded
// backup file. It never connects to the live data directory.
func VerifyCommand(engineID string, p Params, path string) string {
	f := shq(path)
	switch strings.ToLower(engineID) {
	case "postgres":
		return "pg_restore --list " + f + " >/dev/null"
	case "redis":
		return "redis-check-rdb " + f
	case "sqlite":
		return "sqlite3 " + f + " 'PRAGMA quick_check;' | grep -qx ok"
	case "mariadb":
		return "grep -q 'CREATE TABLE' " + f
	case "influxdb", "rclone", "mosquitto", "nats", "victoriametrics", "victorialogs", "ntfy", "pocketbase", "etcd", "meilisearch", "prometheus", "gitea", "beanstalkd":
		return "tar -tzf " + f + " >/dev/null"
	case "duckdb":
		return "test -s " + f
	default:
		return "test -s " + f
	}
}

// ---- helpers ----

func shq(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

// mysqlIdent quotes a MySQL/MariaDB identifier with backticks.
func mysqlIdent(s string) string {
	return "`" + strings.ReplaceAll(s, "`", "``") + "`"
}

func dq(s string) string {
	return `"` + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"`, `\"`) + `"`
}

func pgIdent(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func pgLiteral(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

func port(p Params) int {
	if p.Port > 0 {
		return p.Port
	}
	return 5432
}

// ---- PostgreSQL ----

func postgresInit(p Params) string {
	return fmt.Sprintf(`set -eu
parent=$(dirname %[1]s)
mkdir -p %[1]s
chmod 700 %[1]s
mkdir -p "$parent"
pw="$parent/.phleet-pw-$$"
printf '%%s\n' %[2]s > "$pw"
chmod 600 "$pw"
trap 'rm -f "$pw"' EXIT
initdb -D %[1]s -U %[3]s --pwfile="$pw" \
  --auth-local=trust --auth-host=scram-sha-256 --encoding=UTF8 --locale=C
rm -f "$pw"
trap - EXIT
cat >> %[1]s/postgresql.conf <<'PHLEET_EOF'
listen_addresses = '127.0.0.1'
shared_buffers = 64MB
max_connections = 40
work_mem = 4MB
maintenance_work_mem = 32MB
fsync = on
PHLEET_EOF
cat >> %[1]s/pg_hba.conf <<'PHLEET_EOF'
host replication all 127.0.0.1/32 scram-sha-256
PHLEET_EOF
`, shq(p.DataDir), shq(p.SuperPassword), shq(p.Superuser))
}

func postgresRun(p Params) string {
	return fmt.Sprintf(`exec postgres -D %s -p %d -c listen_addresses=127.0.0.1 -c unix_socket_directories=%s`,
		shq(p.DataDir), port(p), shq(p.DataDir))
}

func postgresHealth(p Params) string {
	return fmt.Sprintf("pg_isready -h 127.0.0.1 -p %d -q", port(p))
}

func postgresPostStart(p Params) string {
	// The setup SQL is written to a file so identifiers and the password never
	// have to survive nested shell quoting. \gexec creates the database
	// conditionally (CREATE DATABASE cannot run inside a DO block).
	replica := ""
	if p.ReplicaUser != "" {
		replica = fmt.Sprintf(`
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = %s) THEN
    CREATE ROLE %s REPLICATION LOGIN PASSWORD %s;
  END IF;
END
$$;`, pgLiteral(p.ReplicaUser), pgIdent(p.ReplicaUser), pgLiteral(p.ReplicaPass))
	}
	return fmt.Sprintf(`set -eu
cat > %[1]s/.phleet-setup.sql <<'PHLEET_SQL'
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = %[2]s) THEN
    CREATE ROLE %[3]s LOGIN PASSWORD %[4]s;
  END IF;
END
$$;
%[9]s
SELECT 'CREATE DATABASE %[5]s OWNER %[3]s'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = %[2]s)
\gexec
PHLEET_SQL
PGPASSWORD=%[6]s psql -h 127.0.0.1 -p %[7]d -U %[8]s -d postgres -v ON_ERROR_STOP=1 -f %[1]s/.phleet-setup.sql
rm -f %[1]s/.phleet-setup.sql
`, shq(p.DataDir), pgLiteral(p.User), pgIdent(p.User), pgLiteral(p.Password),
		pgIdent(p.Database), shq(p.SuperPassword), port(p), shq(p.Superuser), replica)
}

// postgresStandbyInit builds a standby from the running primary over the
// loopback relay. -R writes primary_conninfo and standby.signal for us.
func postgresStandbyInit(p Params, primary Primary) string {
	// Config values are written raw: this is a quoted heredoc, not a shell
	// context, so shell quoting would end up inside the parameter value.
	return fmt.Sprintf(`set -eu
mkdir -p %[1]s
chmod 700 %[1]s
PGPASSWORD=%[2]s pg_basebackup -h %[3]s -p %[4]d -U %[5]s -D %[1]s -Fp -Xs -P -R
cat >> %[1]s/postgresql.auto.conf <<PHLEET_EOF
primary_conninfo = 'host=%[3]s port=%[4]d user=%[5]s password=%[6]s'
recovery_target_timeline = 'latest'
PHLEET_EOF
cat >> %[1]s/postgresql.conf <<'PHLEET_EOF'
listen_addresses = '127.0.0.1'
hot_standby = on
PHLEET_EOF
`, shq(p.DataDir), shq(primary.Password), primary.Host, primary.Port,
		primary.User, primary.Password)
}

func postgresPromote(p Params) string {
	return fmt.Sprintf("pg_ctl promote -D %s", shq(p.DataDir))
}

func postgresPromoteReady(p Params) string {
	return fmt.Sprintf(`PGPASSWORD=%s psql -h 127.0.0.1 -p %d -U %s -d postgres -tAc "select pg_is_in_recovery()" | grep -qx f`,
		shq(p.SuperPassword), port(p), shq(p.Superuser))
}

func postgresLag(p Params) string {
	return fmt.Sprintf(`PGPASSWORD=%s psql -h 127.0.0.1 -p %d -U %s -d postgres -tAc "SELECT COALESCE((EXTRACT(EPOCH FROM replay_lag)*1000)::bigint, -1) FROM pg_stat_replication LIMIT 1"`,
		shq(p.SuperPassword), port(p), shq(p.Superuser))
}

func postgresBackup(p Params, dest string) string {
	return fmt.Sprintf("PGPASSWORD=%s pg_dump -h 127.0.0.1 -p %d -U %s -d %s -Fc -f %s",
		shq(p.Password), port(p), shq(p.User), shq(p.Database), shq(dest))
}

func postgresRestore(p Params, src string) string {
	return fmt.Sprintf("PGPASSWORD=%s pg_restore -h 127.0.0.1 -p %d -U %s -d %s --clean --if-exists --no-owner --no-privileges %s",
		shq(p.Password), port(p), shq(p.User), shq(p.Database), shq(src))
}

func postgresEnv(p Params) map[string]string {
	u := url.URL{
		Scheme:   "postgres",
		User:     url.UserPassword(p.User, p.Password),
		Host:     fmt.Sprintf("127.0.0.1:%d", port(p)),
		Path:     "/" + p.Database,
		RawQuery: "sslmode=disable",
	}
	return map[string]string{
		"DATABASE_URL": u.String(),
		"PGHOST":       "127.0.0.1",
		"PGPORT":       strconv.Itoa(port(p)),
		"PGUSER":       p.User,
		"PGPASSWORD":   p.Password,
		"PGDATABASE":   p.Database,
	}
}

func postgresClient(p Params) string {
	return fmt.Sprintf("PGPASSWORD=%s psql -h 127.0.0.1 -p %d -U %s -d %s --no-psqlrc -v ON_ERROR_STOP=0 -f -",
		shq(p.Password), port(p), shq(p.User), shq(p.Database))
}

