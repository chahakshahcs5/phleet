// ---- S3 object storage (rclone) ----

// rcloneInstall prefers the Termux package and falls back to the static zip.
// MinIO's community binaries were retired in 2025 (dl.min.io returns 410), so
// rclone serve s3 is the maintained, single-binary option.
func rcloneInstall(Params) string {
	return `set -eu
BIN="${PHLEET_STATE_DIR:-$HOME/.phleet}/bin"
if command -v rclone >/dev/null 2>&1; then exit 0; fi
if command -v pkg >/dev/null 2>&1; then
  pkg install -y rclone >/dev/null 2>&1 || true
fi
if command -v rclone >/dev/null 2>&1; then exit 0; fi
case "$(uname -m)" in
  aarch64|arm64) A=arm64 ;;
  x86_64|amd64) A=amd64 ;;
  *) echo "unsupported architecture for rclone"; exit 1 ;;
esac
command -v unzip >/dev/null 2>&1 || { echo "rclone is not installed and unzip is unavailable"; exit 1; }
mkdir -p "$BIN"
cd "$BIN"
curl -fsSL "https://downloads.rclone.org/rclone-current-linux-$A.zip" -o rclone.zip
unzip -o -q rclone.zip
for d in rclone-*-linux-$A; do
  if [ -x "$d/rclone" ]; then cp "$d/rclone" ./rclone.tmp; break; fi
done
chmod 755 ./rclone.tmp
mv ./rclone.tmp ./rclone
rm -rf rclone.zip rclone-*-linux-$A
`
}

func rcloneInit(p Params) string {
	return fmt.Sprintf("mkdir -p %s\n", shq(p.DataDir+"/"+p.Database))
}

func rcloneRun(p Params) string {
	// rclone treats every directory under the served root as a bucket. The
	// path is passed without a remote prefix so no rclone.conf is required.
	// The auth pair is one quoted argument because it contains a comma.
	return fmt.Sprintf(`exec rclone serve s3 --addr 127.0.0.1:%[1]d --auth-key %[2]s --vfs-cache-mode off %[3]s`,
		port(p), shq(p.User+","+p.Password), shq(p.DataDir))
}

func rcloneHealth(p Params) string {
	// An unauthenticated request gets 403; what matters is that the server
	// answers at all.
	return fmt.Sprintf("curl -s -m 3 -o /dev/null http://127.0.0.1:%d/", port(p))
}

func rclonePostStart(p Params) string {
	return fmt.Sprintf("mkdir -p %s\n", shq(p.DataDir+"/"+p.Database))
}

func rcloneBackup(p Params, dest string) string {
	return fmt.Sprintf(`set -eu
tar -czf %s -C %s --exclude='./backups' --exclude='./.phleet-addon' --exclude='./.rclone_temp_*' .
`, shq(dest), shq(p.DataDir))
}

func rcloneRestore(p Params, src string) string {
	bucketDir := p.DataDir + "/" + p.Database
	return fmt.Sprintf(`set -eu
rm -rf %[1]s
mkdir -p %[1]s
tar -xzf %[2]s -C %[3]s
`, shq(bucketDir), shq(src), shq(p.DataDir))
}

