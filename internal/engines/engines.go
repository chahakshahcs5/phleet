// Params is everything an engine needs to render a command. Values are
// generated by the control plane; the agent only renders them.
type Params struct {
	DataDir       string
	File          string // sqlite: absolute database file
	Port          int
	User          string
	Password      string
	Database      string
	Superuser     string
	SuperPassword string
	ReplicaUser   string
	ReplicaPass   string
}

// Primary describes the endpoint a standby should replicate from. On a phone
// this is always a loopback facade port, never the other phone directly.
type Primary struct {
	Host     string
	Port     int
	User     string
	Password string
}

// Engine describes one installable data service. Commands are shell snippets
